#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>
#include <memory.h>
#include <getopt.h>
#include "store.h"

extern char ggpm_source[];
extern int  ggpm_source_len;

int debug_flags = 0;
int stack_size = 1000000;
char *output_fname = 0;
int extended = 0;
FILE *input, *output;

static void error(int rc, const char *msg) {
    fprintf(stderr, "%s\n", msg);
	exit(rc);
}

static void usage() {
    printf("Usage: ggpn2c INPUT OUTPUT\n");
}

static void version() {
    printf("1.0\n");
}

int main (int argc, char **argv) {
    int i, c;

    static struct option long_options[] = {
        {"help",    no_argument,       0, 0},
        {"version", no_argument,       0, 1},
        {"out",     required_argument, 0, 'o'},
        {"stack",   required_argument, 0, 's'},
        {"extended",no_argument,       0, 'e'},
        {0, 0, 0, 0}
    };

    int option_index = 0;

    while((c = getopt_long (argc, argv, "o:s:e", long_options, &option_index)) != -1) {

        switch (c) {
          case 0: /* help */
            usage();
            exit(0);

          case 1: /* version */
            version();
            exit(0);

          case 's':
            if(sscanf(optarg, "%d", &stack_size) != 1 || stack_size < 1000) {
            	fprintf(stderr, "Incorrect -s (--stack) value = %s\n", optarg);
            	exit(1);
            }
            break;

          case 'o':
        	output_fname = optarg;
            break;

          case 'e':
            extended = 1;
            break;

          case '?':
            /* getopt_long() already printed an error message.  */
            break;

          default:
            usage();
            exit(1);
        }
    }

    if (optind + 2 < argc) {
        fprintf(stderr, "Too many arguments\n");
        exit(1);
    }
    input = stdin;
    output = stdout;
    if (optind < argc) {
        input = fopen(argv[optind],"rb");
        if (input == 0)
            error(1, "Cannot open input file");
        optind++;
    }
    if (optind < argc) {
        output = fopen(argv[optind],"wb");
        if (output == 0)
            error(1, "Cannot open output file");
        optind++;
    }

    fprintf(output,
        "/* Generated by ggpm2c */\n"
        "#include <stdio.h>\n"
        "#include <stdlib.h>\n"
        "#include <memory.h>\n"
        "#define getc_prog(f) (pcnt >= sizeof(prog) ? EOF : prog[pcnt++])\n"
        "FILE *input, *output;\n"
        "int extended=1;\n"
    );
  
    fprintf(output,"char prog[]=\n");
    {
        StoreState ss = {0, 0, output};
        while ((c = getc(input)) != EOF) {
            store(c, &ss);
        }
        finish(&ss);
    }
    fprintf(output,";\n");
    fprintf(output,"int pcnt=0;\n");
    {
        int in_char=0, in_string=0;
        int col = 0;
        for (i = 0; i < ggpm_source_len; i++, col++) {
            c = ggpm_source[i];
            putc(c, output);
            switch(c) {
            case '\'':
                if (in_char) {
                    if ((i > 0 && ggpm_source[i - 1] != '\\') || (i > 1 && ggpm_source[i - 2] == '\\'))
                        in_char = 0;
                } else {
                    if (!in_string)
                        in_char = 1;
                }
                break;
            case '"':
                if (in_string) {
                    if ((i > 0 && ggpm_source[i - 1] != '\\') || (i > 1 && ggpm_source[i - 2] == '\\'))
                        in_string = 0;
                } else {
                    if (!in_char)
                        in_string = 1;
                }
                break;
            case ';':
                if (col > 60 && !in_char && !in_string) {
                    putc('\n', output);
                    col = 0;
                }
            }
        }
    }
    fprintf(output,
        "\nint main(){\n"
        "input = stdin;\n"
        "output = stdout;\n"
        "GPM(1000000);\n"
        "return 0;\n"
        "}\n"
    );
  
    if (input != stdin)
        fclose(input);
    if (output != stdout)
        fclose(output);
    return 0;
}
